import type { PiAgentKind } from '../../../shared/agent-launch/catalog/pi-agent-kind'
import { getOmpAcpModeSourceLines } from './omp-acp-mode-source'

export const ORCA_OMP_NATIVE_CHAT_EXTENSION_FILE = 'orca-omp-native-chat.ts'

/** Channel the private notify bridge (orca-omp-native-chat-notify.ts) listens on. */
export const ORCA_OMP_OPTIONS_EVENT = 'orca-omp-options'
export const ORCA_OMP_GENERATION_EVENT = 'orca-omp-generation'

/**
 * OMP native-chat support, public-API half: the `/orca-service-tier` command and
 * the session/generation measurements an Orca ACP chat consumes. Everything here
 * uses the managed extension API only; emitting a bus event is how reports reach
 * the companion notify extension, which owns the private ACP channel.
 */
export function getOmpNativeChatExtensionSource(kind: PiAgentKind): string {
  if (kind !== 'omp') {
    throw new Error(`orca native chat extension only supports OMP sessions, not ${kind}`)
  }
  return [
    'export default function (pi): void {',
    ...getOmpAcpModeSourceLines(),
    '  if (!isAcp) return',
    '  const root = (ctx) => ctx?.agent?.kind === "main"',
    '',
    '  // Mirrors pi-ai serviceTierFamily; the classifier itself is not part of the extension API.',
    '  function serviceTierFamily(model) {',
    '    const provider = model.provider',
    '    if (provider === "openrouter") {',
    '      const klass = model.identity?.class',
    '      if (klass === "anthropic") return "anthropic"',
    '      if (klass === "gemini") return "google"',
    '      if (klass === "openai") return "openai"',
    '      return undefined',
    '    }',
    '    if (provider === "openai" || provider === "openai-codex") return "openai"',
    '    if (model.api === "anthropic-messages") return "anthropic"',
    '    if (provider === "google" || provider === "google-vertex") return "google"',
    '    if (provider !== "fireworks" && provider !== "github-copilot") {',
    '      if (',
    '        (model.api === "openai-completions" ||',
    '          model.api === "openai-responses" ||',
    '          model.api === "openai-codex-responses") &&',
    '        model.identity?.class === "openai"',
    '      ) {',
    '        return "openai"',
    '      }',
    '    }',
    '    return undefined',
    '  }',
    '',
    '  // Mirrors pi-coding-agent config/service-tier OPTION constants verbatim.',
    '  const SERVICE_TIER_OPENAI_OPTIONS = [',
    '    { value: "none", label: "None", description: "Omit service_tier (standard processing)" },',
    '    { value: "auto", label: "Auto", description: "Provider default tier selection" },',
    '    { value: "default", label: "Default", description: "Standard priority processing" },',
    '    {',
    '      value: "flex",',
    '      label: "Flex",',
    '      description: "Lower cost, higher latency when available"',
    '    },',
    '    { value: "scale", label: "Scale", description: "Scale Tier credits when available" },',
    '    {',
    '      value: "priority",',
    '      label: "Priority",',
    '      description: "Faster, higher cost (premium request)"',
    '    },',
    '    {',
    '      value: "ultrafast",',
    '      label: "Ultrafast",',
    '      description:',
    '        "Lowest-latency serving; OpenAI API preview access, or Codex and relay models that advertise it"',
    '    }',
    '  ]',
    '  const SERVICE_TIER_ANTHROPIC_OPTIONS = [',
    '    { value: "none", label: "None", description: "Standard processing" },',
    '    {',
    '      value: "priority",',
    '      label: "Priority",',
    '      description:',
    '        \'Fast mode (`speed: "fast"`) on supported direct Claude models; ignored on Bedrock/Vertex\'',
    '    }',
    '  ]',
    '  const SERVICE_TIER_GOOGLE_OPTIONS = [',
    '    { value: "none", label: "None", description: "Standard processing" },',
    '    {',
    '      value: "flex",',
    '      label: "Flex",',
    '      description: "Lower cost, higher latency (Gemini API + Vertex)"',
    '    },',
    '    {',
    '      value: "priority",',
    '      label: "Priority",',
    '      description: "Faster, higher reliability (Gemini API + Vertex)"',
    '    }',
    '  ]',
    '  const choices = {',
    '    openai: SERVICE_TIER_OPENAI_OPTIONS,',
    '    anthropic: SERVICE_TIER_ANTHROPIC_OPTIONS,',
    '    google: SERVICE_TIER_GOOGLE_OPTIONS',
    '  }',
    '',
    '  const reportOptions = (ctx) => {',
    '    if (!root(ctx) || typeof pi.getServiceTiers !== "function" || !pi.events) return',
    '    const tiers = pi.getServiceTiers()',
    `    pi.events.emit('${ORCA_OMP_OPTIONS_EVENT}', {`,
    '      models: ctx.modelRegistry.getAvailable().map((model) => {',
    '        const family = serviceTierFamily(model)',
    '        return {',
    '          id: `${model.provider}/${model.id}`,',
    '          serviceTiers: choices[family] ?? [],',
    '          serviceTier: family ? (tiers[family] ?? "none") : null',
    '        }',
    '      })',
    '    })',
    '  }',
    '',
    '  pi.on("session_start", (_event, ctx) => reportOptions(ctx))',
    '  pi.on("session_switch", (_event, ctx) => reportOptions(ctx))',
    '  pi.on("before_agent_start", (_event, ctx) => reportOptions(ctx))',
    '  pi.registerCommand("orca-service-tier", {',
    '    description: "Set the service tier selected in Orca",',
    '    handler: (value, ctx) => {',
    '      if (!root(ctx)) return',
    '      const tier = value.trim()',
    '      const model = ctx.model',
    '      const family = model && serviceTierFamily(model)',
    '      if (!choices[family]?.some((choice) => choice.value === tier)) {',
    '        throw new Error("This model has no matching native service tier")',
    '      }',
    '      pi.setServiceTier(family, tier === "none" ? undefined : tier)',
    '      reportOptions(ctx)',
    '    }',
    '  })',
    '',
    '  let outputTokens = 0',
    '  let durationMs = 0',
    '  let measured = true',
    '  let requestStartedAt',
    '  pi.on("agent_start", (_event, ctx) => {',
    '    if (!root(ctx)) return',
    '    outputTokens = 0',
    '    durationMs = 0',
    '    measured = true',
    '    requestStartedAt = undefined',
    '  })',
    '  pi.on("before_provider_request", (_event, ctx) => {',
    '    if (root(ctx)) {',
    '      requestStartedAt = performance.now()',
    '    }',
    '  })',
    '  pi.on("message_end", ({ message }, ctx) => {',
    '    if (!root(ctx) || message.role !== "assistant" || !pi.events) return',
    '    const tokens = message.usage?.output',
    '    const elapsed =',
    '      requestStartedAt === undefined ? undefined : performance.now() - requestStartedAt',
    '    requestStartedAt = undefined',
    '    const duration = message.duration ?? elapsed',
    '    // Synthetic assistant notices have no provider request or output to measure.',
    '    if (tokens === 0 && duration === undefined) return',
    '    measured &&= Number.isFinite(tokens) && tokens >= 0 && Number.isFinite(duration) && duration > 0',
    '    if (!measured) return',
    '    outputTokens += tokens',
    '    durationMs += duration',
    '    if (outputTokens > 0 && durationMs > 0) {',
    `      pi.events.emit('${ORCA_OMP_GENERATION_EVENT}', { outputTokens, durationMs })`,
    '    }',
    '  })',
    '  pi.on("agent_end", (_event, ctx) => reportOptions(ctx))',
    '}'
  ].join('\n')
}
